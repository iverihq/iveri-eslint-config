const globals = require('globals');

const { base } = require('./base');

/**
 * NestJS services. Adds node + jest globals and relaxes the handful of rules that
 * fight the framework's own idioms rather than catching real defects.
 */
const nest = [
    ...base,
    {
        files: ['**/*.ts'],
        languageOptions: {
            globals: {
                ...globals.node,
                ...globals.jest,
            },
        },
        rules: {
            // `@Module({})` classes have no members by design.
            '@typescript-eslint/no-extraneous-class': 'off',
            // Decorator factories are declared as `unknown`-returning by Nest itself.
            '@typescript-eslint/no-unsafe-argument': 'error',
            '@typescript-eslint/unbound-method': ['error', { ignoreStatic: true }],
        },
    },
    {
        // Migrations are generated by TypeORM; their shape is not ours to restyle.
        files: ['**/db-migration/**/*.ts'],
        rules: {
            '@typescript-eslint/naming-convention': 'off',
            '@typescript-eslint/no-unnecessary-condition': 'off',
        },
    },
    {
        // Jest's matchers are typed loosely (`expect.any`, `objectContaining` return `any`) and
        // test doubles are deliberately partial. Enforcing the strict-typing rules here buys
        // nothing and pushes people towards `eslint-disable`, which is worse.
        files: ['**/*.spec.ts', '**/*.e2e-spec.ts', '**/test/**/*.ts'],
        rules: {
            '@typescript-eslint/no-non-null-assertion': 'off',
            '@typescript-eslint/no-unsafe-assignment': 'off',
            '@typescript-eslint/no-unsafe-argument': 'off',
            '@typescript-eslint/no-unsafe-call': 'off',
            '@typescript-eslint/no-unsafe-member-access': 'off',
            '@typescript-eslint/explicit-function-return-type': 'off',
            '@typescript-eslint/no-unnecessary-condition': 'off',
        },
    },
];

module.exports = { nest };
